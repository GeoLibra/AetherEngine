import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { format } from 'prettier';

import { defineShaderAuthoringSource } from '../src/shader/authoring';
import { cookAuthoredShader } from '../tools/shader-cooker/authoring-dispatch';

const ROOT = resolve(import.meta.dirname, '..');
const SOURCE_PATH = resolve(ROOT, 'src/shader/builtins/standard-lit.wgsl');
const METADATA_PATH = resolve(ROOT, 'src/shader/builtins/standard-lit.wgsl.meta.json');
const OUTPUT_PATH = resolve(ROOT, 'src/shader/builtins/standard-lit.generated.ts');
const SOURCE_URI = 'asset://aether/builtins/standard-lit.wgsl';

const artifact = await cookAuthoredShader({
  source: defineShaderAuthoringSource({ kind: 'wgsl', uri: SOURCE_URI, languageVersion: 'wgsl-1' }),
  sourcePath: SOURCE_PATH,
  metadataPath: METADATA_PATH
});
const artifactLiteral = JSON.stringify(artifact, null, 2);
const generated = await format(
  `/* This file is generated by scripts/cook-built-in-shaders.ts. Do not edit. */
import { decodeCookedShaderRuntimeArtifact } from '../artifact';

export const STANDARD_LIT_SHADER_GENERATED_ARTIFACT =
  decodeCookedShaderRuntimeArtifact(${artifactLiteral});
`,
  { parser: 'typescript', singleQuote: true, trailingComma: 'none', semi: true, printWidth: 100 }
);

if (process.argv.includes('--check')) {
  const published = await readFile(OUTPUT_PATH, 'utf8').catch(() => '');
  if (published !== generated)
    throw new Error('Built-in shader artifacts are stale. Run "pnpm run shader:generate".');
} else {
  await writeFile(OUTPUT_PATH, generated, 'utf8');
}
