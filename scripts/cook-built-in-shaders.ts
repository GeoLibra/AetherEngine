import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { format } from 'prettier';

import { InMemoryShaderSourceResolver } from '../src/shader/frontend/source-resolver';
import { AETHER_SHADER_STANDARD_LIBRARY_VERSION } from '../src/shader/frontend/standard-library';
import { cookShaderArtifact } from '../src/shader/pipeline/cook';

const ROOT = resolve(import.meta.dirname, '..');
const SOURCE_PATH = resolve(ROOT, 'src/shader/builtins/standard-lit.flux');
const OUTPUT_PATH = resolve(ROOT, 'src/shader/builtins/standard-lit.generated.ts');
const SOURCE_URI = 'asset://aether/builtins/standard-lit.flux';
const ABI_VERSION = 1;

const sourceText = await readFile(SOURCE_PATH, 'utf8');
const resolver = new InMemoryShaderSourceResolver({ [SOURCE_URI]: sourceText });
const artifact = await cookShaderArtifact({ uri: SOURCE_URI, languageVersion: 1 }, resolver, {
  compiler: 1,
  ir: 1,
  abi: ABI_VERSION,
  standardLibrary: AETHER_SHADER_STANDARD_LIBRARY_VERSION
});
const moduleLiteral = JSON.stringify(artifact.ir, null, 2);
const generated = await format(
  `/* This file is generated by scripts/cook-built-in-shaders.ts. Do not edit. */
import type { ShaderModuleIR } from '../types';
import { freezeGeneratedShaderModule } from './generated-runtime';

export const STANDARD_LIT_SHADER_SOURCE_TEXT = ${JSON.stringify(sourceText)};

export const STANDARD_LIT_SHADER_GENERATED_MODULE: ShaderModuleIR =
  freezeGeneratedShaderModule(${moduleLiteral} as unknown as ShaderModuleIR);
`,
  { parser: 'typescript', singleQuote: true, trailingComma: 'none', semi: true, printWidth: 100 }
);

if (process.argv.includes('--check')) {
  const published = await readFile(OUTPUT_PATH, 'utf8').catch(() => '');
  if (published !== generated)
    throw new Error('Built-in shader artifacts are stale. Run "pnpm run shader:generate".');
} else {
  await writeFile(OUTPUT_PATH, generated, 'utf8');
}
